// Простая эвристика по ключевым словам в комментарии — без ИИ и сети, поэтому работает офлайн
// и мгновенно. Если ни одно слово не совпало, suggestCategory() вернёт undefined, и категория
// не будет подставлена автоматически.
const EXPENSE_KEYWORDS: Record<string, string[]> = {
  'Продукты': ['продукт', 'магазин', 'пятерочка', 'перекресток', 'ашан', 'вкусвилл'],
  'Одежда': ['одежда', 'обувь', 'zara', 'hm', 'куртка'],
  'Маркетплейсы': ['wildberries', 'ozon', 'озон', 'вайлдберриз', 'маркетплейс'],
  'Транспорт': ['такси', 'метро', 'автобус', 'проезд', 'яндекс go'],
  'Бензин': ['бензин', 'заправка', 'азс'],
  'Жильё': ['аренда', 'квартплата', 'коммуналка', 'жкх'],
  'Здоровье': ['аптека', 'врач', 'клиника', 'больница', 'лекарств'],
  'Развлечения': ['кино', 'театр', 'концерт', 'развлечен'],
  'Образование': ['курс', 'обучение', 'книга', 'учеба'],
  'Рестораны': ['кафе', 'ресторан', 'кофейня', 'бар'],
  'Связь': ['мобильная связь', 'мтс', 'билайн', 'мегафон', 'теле2'],
  'Подписки': ['подписка', 'netflix', 'spotify', 'youtube premium'],
  'Дом/Ремонт': ['ремонт', 'леруа', 'стройматериал'],
  'Подарки': ['подарок', 'подарки'],
  'Спорт': ['спортзал', 'фитнес', 'тренаж', 'абонемент в зал', 'бассейн'],
  'Рабочие обеды': ['рабочий обед', 'бизнес-ланч', 'бизнес ланч', 'обед на работе'],
};

const INCOME_KEYWORDS: Record<string, string[]> = {
  'Зарплата': ['зарплата', 'зп', 'оклад'],
  'Премия': ['премия', 'бонус'],
  'Доп. работа': ['подработка', 'доп. работа', 'фриланс проект'],
  'Инвестиции': ['дивиденд', 'инвестиц'],
  'Кэшбэк': ['кэшбэк', 'кешбек'],
  'Подарки': ['подарок'],
  'Аренда': ['сдача', 'аренда квартиры'],
  'Фриланс': ['фриланс'],
  'Проценты по вкладам': ['проценты', 'вклад'],
};

export function suggestCategory(comment: string, type: 'income' | 'expense'): string | undefined {
  if (!comment || comment.trim().length === 0) return undefined;
  const lower = comment.toLowerCase();
  const dictionary = type === 'expense' ? EXPENSE_KEYWORDS : INCOME_KEYWORDS;

  for (const [category, keywords] of Object.entries(dictionary)) {
    if (keywords.some((keyword) => lower.includes(keyword))) {
      return category;
    }
  }
  return undefined;
}
